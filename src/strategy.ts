import deepReplace, { BuildExtras } from './deep-replace';
import { forEachItems, forEachVariables, normaliseVariables, POSITION_NAMES } from './variables';
import { isRegistrySource, resolveRegistryItems, SourceContext } from './registry';
import { sourceTemplate, TemplateRender } from './template-source';
import { CONSUMER_TYPES } from './templates';
import { VariablesConfig } from './types';

// What a strategy's substitutions are handed for `with:` and `repeat:` (#227): the item
// templates ride on the context the card already builds, and the context itself serves a
// `repeat:` over a registry source.
const extrasOf = (context?: SourceContext): BuildExtras => ({ itemTemplates: context?.itemTemplates, context });

/* eslint-disable @typescript-eslint/no-explicit-any */

/*
 * A view that builds itself. A card can only repeat inside the one slot it was given, so a
 * repeat over the house's rooms lands in a single section however wide the screen is - the
 * sections never reflow, and none of them gets a heading or a background of its own. Home
 * Assistant lets a view be generated by a strategy instead, and a generated view is laid
 * out by Home Assistant like any other. So the strategy writes the view out - a section,
 * or a badge, per item - and Home Assistant does the rest.
 *
 *   strategy:
 *     type: custom:decluttering-card-plus
 *     sections:
 *       - for_each_from: { areas: true }
 *         section:
 *           type: grid
 *           cards:
 *             - type: heading
 *               heading: '[[name]]'
 *             - type: custom:decluttering-card-plus
 *               template: room_lights
 *
 * An entry with nothing to repeat over is passed through as written, so a repeat sits
 * among ordinary sections and badges. Everything else in the strategy is the view's own.
 */

/** The strategy's own keys - the rest of what it says is the view. */
const OWN_KEYS = ['type', 'variables', 'sections', 'badges'];

/** Whether an entry asks to be repeated, rather than being a section or badge as written. */
export function isRepeatEntry(entry: any): boolean {
  if (!entry || typeof entry !== 'object' || Array.isArray(entry)) return false;
  return entry.for_each !== undefined || entry.for_each_from !== undefined;
}

/** The items an entry repeats over - a list written out, or what Home Assistant knows. */
function entryItems(entry: any, hass: any, context?: SourceContext): unknown[] {
  const written = forEachItems(entry.for_each);
  if (written) return written;
  return isRegistrySource(entry.for_each_from) ? resolveRegistryItems(hass, entry.for_each_from, context) : [];
}

/*
 * A templated card inside a copy is handed that copy's values too, so a section can hold
 * `template: room_lights` and nothing else - the area it is for arrives on its own. The
 * card's own values come first, so anything it says for itself still wins. A template
 * card's content is never touched: that is a definition, not a use.
 */
function handDown(node: any, values: VariablesConfig[]): any {
  if (Array.isArray(node)) return node.map((item) => handDown(item, values));
  if (!node || typeof node !== 'object') return node;
  if (CONSUMER_TYPES.includes(node.type)) {
    return { ...node, variables: [...normaliseVariables(node.variables), ...values] };
  }
  const out: any = {};
  for (const [key, value] of Object.entries(node)) out[key] = handDown(value, values);
  return out;
}

/**
 * One entry of `sections:` or `badges:`, as the list of sections or badges it stands for:
 * itself when it repeats nothing, one copy per item when it does, and its `empty:` when a
 * repeat matches nothing at all.
 */
export function expandEntry(
  entry: any,
  kind: 'section' | 'badge',
  shared: unknown,
  hass?: any,
  context?: SourceContext,
): any[] {
  if (!isRepeatEntry(entry)) return [entry];
  const content = entry[kind];
  if (content === undefined) return [];

  const items = entryItems(entry, hass, context);
  if (!items.length) return entry.empty === undefined ? [] : [entry.empty];

  const common = [...normaliseVariables(entry.variables), ...normaliseVariables(shared)];
  return items.map((item, index) => {
    const values = forEachVariables(item, common, index, items.length);
    return handDown(
      deepReplace(
        values,
        {},
        content,
        undefined,
        hass,
        undefined,
        undefined,
        0,
        undefined,
        undefined,
        false,
        extrasOf(context),
      ),
      values,
    );
  });
}

/** The view a strategy config describes, with every repeat written out. */
export function generateView(config: any, hass?: any, context?: SourceContext): any {
  const view: any = {};
  for (const [key, value] of Object.entries(config ?? {})) {
    if (!OWN_KEYS.includes(key)) view[key] = value;
  }

  const expand = (list: unknown, kind: 'section' | 'badge'): any[] =>
    ([] as any[]).concat(
      ...(Array.isArray(list) ? list : []).map((entry: any) =>
        expandEntry(entry, kind, config?.variables, hass, context),
      ),
    );

  if (config?.badges !== undefined) view.badges = expand(config.badges, 'badge');
  if (config?.sections !== undefined) {
    view.sections = expand(config.sections, 'section');
    // Sections only mean anything in a sections view, so that is what asking for them gets.
    view.type ??= 'sections';
  }
  return view;
}

/**
 * Every `for_each_from: { template: }` among the strategy's sections and badges, rendered
 * once each - the same Jinja twice is asked about once - keyed by the template's text.
 */
export async function renderStrategyTemplates(
  config: any,
  render: (template: string) => Promise<TemplateRender>,
): Promise<Record<string, TemplateRender>> {
  const rendered: Record<string, TemplateRender> = {};
  const entries: any[] = ([] as any[]).concat(
    ...[config?.sections, config?.badges].map((list) => (Array.isArray(list) ? list : [])),
  );
  for (const entry of entries) {
    const template = sourceTemplate(entry?.for_each_from);
    if (template === undefined || Object.prototype.hasOwnProperty.call(rendered, template)) continue;
    rendered[template] = await render(template);
  }
  return rendered;
}

/** Whether a repeat in the strategy reads labels, which have to be fetched before it runs. */
export function wantsLabels(config: any): boolean {
  return /label/i.test(JSON.stringify([config?.sections, config?.badges]));
}

/*
 * The same idea one level up: a whole dashboard that writes itself out, a view per item.
 * A dashboard of rooms is the same view over and over with a different area in it, and
 * the view strategy above can only ever be one of those views.
 *
 *   strategy:
 *     type: custom:decluttering-card-plus
 *     decluttering_templates: { ... }
 *     views:
 *       - title: Home
 *         cards: [...]
 *       - for_each_from: { areas: true }
 *         view:
 *           title: '[[area]]'
 *           path: '[[area_id]]'
 *           sections: [...]
 *
 * Home Assistant only ever sees the dashboard this writes, so the cards in it look for
 * their templates there - which is why the template keys are copied to its root rather
 * than kept in the strategy, where nothing would read them.
 */

/** The dashboard strategy's own keys - everything else it says goes to the dashboard's root. */
const DASHBOARD_OWN_KEYS = ['type', 'variables', 'views'];

/** The custom type both strategies answer to, and the one a nested view strategy is recognised by. */
export const STRATEGY_TYPE = 'custom:decluttering-card-plus';

// What a repeat entry holds for each copy, which the copy's own item fills - not the view around it.
const REPEAT_CONTENT_KEYS = ['section', 'badge', 'empty'];

/*
 * A view's path is a piece of its address, so what a placeholder fills in - an area called
 * "Living Room" - is made fit for one. A path of only digits would be read by Home
 * Assistant as a view's position rather than its name, so it is given a word in front.
 */
export function slugPath(path: unknown): string | undefined {
  if (path === undefined || path === null) return undefined;
  const slug = String(path)
    .toLowerCase()
    .replace(/[^a-z0-9_-]+/g, '-')
    .replace(/-{2,}/g, '-')
    .replace(/^-+|-+$/g, '');
  if (!slug) return undefined;
  return /^\d+$/.test(slug) ? `view-${slug}` : slug;
}

/** `path`, or the first `path-2`, `path-3`... nothing in `taken` has yet. Taken as it is handed out. */
export function uniquePath(path: string, taken: Set<string>): string {
  let unique = path;
  for (let counter = 2; taken.has(unique); counter += 1) unique = `${path}-${counter}`;
  taken.add(unique);
  return unique;
}

/*
 * A view strategy inside a repeated view runs after this one, over items of its own. The
 * view's values reach it two ways. What it repeats over is filled in here, so a view per
 * area can repeat over that area's lights - `area: '[[area_id]]'`. What it repeats is not:
 * that belongs to the inner items, and filling it here would let the area's `name` beat
 * the light's. The view's values go in as the inner strategy's shared values instead,
 * which an inner item still beats - minus the position, which is the inner repeat's own.
 */
function fillNestedStrategy(strategy: any, values: VariablesConfig[], hass: any, context?: SourceContext): any {
  const held = new Map<string, Record<string, unknown>>();
  const skeleton: any = { ...strategy };
  for (const key of ['sections', 'badges']) {
    if (!Array.isArray(strategy[key])) continue;
    skeleton[key] = strategy[key].map((entry: any, index: number) => {
      if (!isRepeatEntry(entry)) return entry;
      const kept: Record<string, unknown> = {};
      const rest: any = {};
      for (const [name, value] of Object.entries(entry)) {
        if (REPEAT_CONTENT_KEYS.includes(name)) kept[name] = value;
        else rest[name] = value;
      }
      held.set(`${key}:${index}`, kept);
      return rest;
    });
  }
  const filled = deepReplace(
    values,
    {},
    skeleton,
    undefined,
    hass,
    undefined,
    undefined,
    0,
    undefined,
    undefined,
    false,
    extrasOf(context),
  );
  for (const key of ['sections', 'badges']) {
    if (!Array.isArray(filled[key])) continue;
    filled[key] = filled[key].map((entry: any, index: number) => ({ ...entry, ...held.get(`${key}:${index}`) }));
  }
  const positionless = values.filter((entry) => !POSITION_NAMES.includes(Object.keys(entry)[0]));
  filled.variables = [...normaliseVariables(filled.variables), ...positionless];
  return filled;
}

/** One view of a repeat, filled in with its item's values. */
function fillView(content: any, values: VariablesConfig[], hass: any, context?: SourceContext): any {
  if (!content || typeof content !== 'object' || Array.isArray(content)) return content;
  const { strategy, ...rest } = content;
  const extras = extrasOf(context);
  const view = handDown(
    deepReplace(values, {}, rest, undefined, hass, undefined, undefined, 0, undefined, undefined, false, extras),
    values,
  );
  if (strategy === undefined) return view;
  // Somebody else's strategy is filled in like any other part of the view, and left to run.
  view.strategy =
    strategy?.type === STRATEGY_TYPE
      ? fillNestedStrategy(strategy, values, hass, context)
      : deepReplace(
          values,
          {},
          strategy,
          undefined,
          hass,
          undefined,
          undefined,
          0,
          undefined,
          undefined,
          false,
          extras,
        );
  return view;
}

/** One entry of a dashboard's `views:`, as the views it stands for - the way expandEntry does sections. */
export function expandView(entry: any, shared: unknown, hass?: any, context?: SourceContext): any[] {
  if (!isRepeatEntry(entry)) return [entry];
  if (entry.view === undefined) return [];

  const items = entryItems(entry, hass, context);
  if (!items.length) return entry.empty === undefined ? [] : [entry.empty];

  const common = [...normaliseVariables(entry.variables), ...normaliseVariables(shared)];
  return items.map((item, index) =>
    fillView(entry.view, forEachVariables(item, common, index, items.length), hass, context),
  );
}

/*
 * The strategy's `variables:` reach the rest of the dashboard too - its own settings, such as
 * a `wallpanel:` block, and the views written out as they are - not only the repeats (#226).
 * The template keys are definitions, filled in later by each card that uses them, so they
 * are left alone. Quietly: a placeholder nothing here sets may well be a card's own, or
 * button-card's `[[[ ]]]`, and stays as written for whoever reads it next.
 */
function fillPlain(content: any, values: VariablesConfig[], hass: any): any {
  if (!values.length) return content;
  if (!content || typeof content !== 'object' || Array.isArray(content) || content.strategy === undefined) {
    return deepReplace(values, {}, content, undefined, hass, true);
  }
  const { strategy, ...rest } = content;
  const view = deepReplace(values, {}, rest, undefined, hass, true);
  view.strategy =
    strategy?.type === STRATEGY_TYPE
      ? fillNestedStrategy(strategy, values, hass)
      : deepReplace(values, {}, strategy, undefined, hass, true);
  return view;
}

/** The dashboard a dashboard strategy config describes, with every repeated view written out. */
export function generateDashboard(config: any, hass?: any, context?: SourceContext): any {
  const shared = normaliseVariables(config?.variables);
  const dashboard: any = {};
  for (const [key, value] of Object.entries(config ?? {})) {
    if (DASHBOARD_OWN_KEYS.includes(key)) continue;
    dashboard[key] = key.startsWith('decluttering_') ? value : fillPlain(value, shared, hass);
  }

  const entries: any[] = (Array.isArray(config?.views) ? config.views : []).map((entry: any) =>
    isRepeatEntry(entry) ? entry : fillPlain(entry, shared, hass),
  );
  // A path written out by hand is the user's and is kept as written; a generated one makes
  // way for it, wherever in the list either sits.
  const taken = new Set<string>();
  for (const entry of entries) {
    if (!isRepeatEntry(entry) && typeof entry?.path === 'string' && entry.path) taken.add(entry.path);
  }

  const pathed = (view: any): any => {
    if (!view || typeof view !== 'object' || view.path === undefined) return view;
    const out = { ...view };
    const slug = slugPath(view.path);
    if (slug) out.path = uniquePath(slug, taken);
    else delete out.path;
    return out;
  };
  dashboard.views = ([] as any[]).concat(
    ...entries.map((entry) =>
      isRepeatEntry(entry) ? expandView(entry, config?.variables, hass, context).map(pathed) : [entry],
    ),
  );
  return dashboard;
}

/** Whether a repeated view reads labels, which have to be fetched before the dashboard is written. */
export function dashboardWantsLabels(config: any): boolean {
  return /label/i.test(JSON.stringify(config?.views ?? null));
}

/** The card options that shape a repeat inside one card, and mean nothing once each copy has a section. */
const IN_CARD_REPEAT_KEYS = ['for_each', 'for_each_from', 'columns', 'min_column_width', 'gap', 'empty'];

/**
 * Where a repeating card sits: the view, and the section it is directly in. Only a card
 * written straight into a section of an ordinary sections view qualifies - one in a stack
 * is somebody's layout, and a view the strategy already writes has nothing to convert.
 */
export function findRepeatingCard(ll: any, card: any): { view: number; section: number; card: number } | undefined {
  if (!isRepeatEntry(card)) return undefined;
  const wanted = JSON.stringify(card);
  const views: any[] = Array.isArray(ll?.views) ? ll.views : [];
  for (let view = 0; view < views.length; view += 1) {
    if (views[view]?.strategy || !Array.isArray(views[view]?.sections)) continue;
    const sections: any[] = views[view].sections;
    for (let section = 0; section < sections.length; section += 1) {
      const cards: any[] = Array.isArray(sections[section]?.cards) ? sections[section].cards : [];
      const index = cards.findIndex((each) => JSON.stringify(each) === wanted);
      if (index !== -1) return { view, section, card: index };
    }
  }
  return undefined;
}

/**
 * The dashboard with a repeating card's view handed to the strategy, and the card's
 * section repeated in its place - one section per copy, each holding the card once. The
 * rest of that section stays where it was as a section of its own, and every other
 * section and badge in the view goes into the strategy exactly as written.
 *
 * Nothing is mutated; the caller gets a new configuration to save, or the same one back
 * when the card is not somewhere this can work.
 */
export function sectionPerCopy(ll: any, card: any): any {
  const place = findRepeatingCard(ll, card);
  if (!place) return ll;

  const view = ll.views[place.view];
  const section = view.sections[place.section];
  const others = section.cards.filter((_: unknown, index: number) => index !== place.card);

  const once: any = {};
  for (const [key, value] of Object.entries(card)) if (!IN_CARD_REPEAT_KEYS.includes(key)) once[key] = value;

  const repeat: any = {};
  if (card.for_each !== undefined) repeat.for_each = card.for_each;
  else repeat.for_each_from = card.for_each_from;
  repeat.section = { ...section, cards: [once] };
  if (card.empty !== undefined) repeat.empty = { ...section, cards: [card.empty] };

  const sections = view.sections.flatMap((each: any, index: number) =>
    index !== place.section ? [each] : others.length ? [{ ...section, cards: others }, repeat] : [repeat],
  );

  const rest: any = { ...view };
  const badges = rest.badges;
  delete rest.sections;
  delete rest.badges;
  const strategy: any = { type: 'custom:decluttering-card-plus' };
  if (badges !== undefined) strategy.badges = badges;
  strategy.sections = sections;

  return {
    ...ll,
    views: ll.views.map((each: any, index: number) => (index === place.view ? { ...rest, strategy } : each)),
  };
}
